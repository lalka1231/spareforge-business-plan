def readable(markdown):
    """Separate jammed prose tokens; preserve inline/fenced code verbatim."""
    lines=[]
    fenced=False
    for line in markdown.splitlines():
        if line.startswith('```'):
            fenced=not fenced
            lines.append(line)
            continue
        if fenced:
            lines.append(line)
            continue
        pieces=re.split(r'(`[^`]*`)',line)
        for i,piece in enumerate(pieces):
            if piece.startswith('`'):
                continue
            piece=re.sub(r'([А-Яа-яЁё])(?=[0-9A-Za-z])',r'\1 ',piece)
            piece=re.sub(r'([0-9A-Za-z])(?=[А-Яа-яЁё])',r'\1 ',piece)
            piece=re.sub(r'([0-9])(?=₽)',r'\1 ',piece)
            piece=re.sub(r'(NPV|FCF|EBITDA|CAPEX|OPEX)(?=\d)',r'\1 ',piece)
            pieces[i]=piece
        lines.append(''.join(pieces))
    return '\n'.join(lines)+'\n'

